import { callGroqJson, assertNoUrls } from '../../src/lib/foundation';
import { LEARNING_CONFIG } from '../../src/config/learning';

async function main() {
  console.log('=== T5: GAME PLAN & PEDAGOGICAL BRIEF AUDIT ===\n');

  const mockResources = [
    { id: 'res-doc-1', type: 'doc', title: 'Roblox Lua Architecture', domain: 'roblox.com', snippet: 'Guide to Luau typechecking and server-client networking.' },
    { id: 'res-vid-1', type: 'video', title: 'RemoteEvents and RemoteFunctions Masterclass', domain: 'youtube.com', snippet: 'Walkthrough of firing remote events across network boundaries.' },
  ];

  const mockTopics = [
    { key: 't1', title: 'Client-Server Invariants' },
    { key: 't2', title: 'Remote Event Security' },
  ];

  const planPrompt = `You are a Principal Curriculum Director designing a "how to approach this milestone" game plan for a learner studying:
Skill: Roblox Studio Development
Milestone: Client-Server Replication
Tier: INTERMEDIATE_FLUIDITY
Topics: ${JSON.stringify(mockTopics)}
Assigned Resources: ${JSON.stringify(mockResources)}

Return strictly JSON matching:
{
  "goal": "one direct sentence",
  "whyNow": "one direct sentence",
  "totalMinutes": 35,
  "order": [{"topicKey": "t1", "why": "..."}],
  "beforeYouStart": ["prediction 1", "prediction 2"],
  "perResource": [
    {"resourceId": "res-doc-1", "focus": "...", "ignore": "...", "timebox": "15 min"},
    {"resourceId": "res-vid-1", "focus": "...", "ignore": "...", "timebox": "20 min"}
  ],
  "howToStudy": ["technique 1", "technique 2", "technique 3"],
  "commonMistakes": ["mistake 1", "mistake 2"],
  "selfCheck": [
    {"prompt": "question 1", "hint": "hint 1"},
    {"prompt": "question 2", "hint": "hint 2"},
    {"prompt": "question 3", "hint": "hint 3"}
  ]
}
Rules:
- Resource IDs must match assigned resources exactly.
- DO NOT INCLUDE ANY URLS.
- DO NOT INCLUDE ANY TIMESTAMPS (such as 02:15 or 10:30).
- Max 25 words per bullet. Direct, encouraging tone.`;

  const brief = await callGroqJson<any>(
    'You are a Principal Curriculum Director. Return valid JSON only.',
    planPrompt,
    { maxTokens: 1800, temperature: 0.2 }
  );

  // 1. Verify assertNoUrls passes
  console.log('[T5.1] URL Safety Audit:');
  assertNoUrls(brief, 'ApproachBrief');
  console.log('  assertNoUrls check passed: Zero URLs generated by model (Expected: Pass)');

  // 2. Timestamp check
  console.log('\n[T5.2] Timestamp Format Check:');
  const briefStr = JSON.stringify(brief);
  const timestampRegex = /\b\d{1,2}:\d{2}\b/;
  const hasTimestamps = timestampRegex.test(briefStr);
  console.log(`  Contains video timestamps (e.g. 05:20)? ${hasTimestamps} (Expected: false)`);

  // 3. Resource ID alignment
  console.log('\n[T5.3] Resource IDs Validation:');
  const allowedIds = new Set(mockResources.map(r => r.id));
  const referencedIds = (brief.perResource || []).map((p: any) => p.resourceId);
  const allIdsValid = referencedIds.every((id: string) => allowedIds.has(id));
  console.log(`  Referenced resource IDs: ${JSON.stringify(referencedIds)}`);
  console.log(`  All IDs belong to assigned resources? ${allIdsValid} (Expected: true)`);

  // 4. Mastery target pass percent rule
  console.log('\n[T5.4] Mastery Target Threshold Rule:');
  const briefWithMastery = {
    ...brief,
    masteryTarget: { passPercent: LEARNING_CONFIG.PASS_THRESHOLD_PERCENT },
  };
  console.log(`  masteryTarget.passPercent: ${briefWithMastery.masteryTarget.passPercent}%`);
  console.log(`  Matches LEARNING_CONFIG.PASS_THRESHOLD_PERCENT (${LEARNING_CONFIG.PASS_THRESHOLD_PERCENT})? ${briefWithMastery.masteryTarget.passPercent === LEARNING_CONFIG.PASS_THRESHOLD_PERCENT} (Expected: true)`);

  console.log('\n[T5 RESULT] ALL GAME PLAN PEDAGOGICAL INVARIANTS SATISFIED.');
}

main().catch(err => {
  console.error('Game plan test error:', err);
  process.exit(1);
});
